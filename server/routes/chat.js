    const hasPortrait = butlerResult.portrait &&
      (Array.isArray(butlerResult.portrait) ? butlerResult.portrait.length > 0 : !!butlerResult.portrait.name);
    const hasCG = butlerResult.triggerImage && butlerResult.imagePrompt;

    if (!hasPortrait && !hasCG) {
      console.log('[Painter] No portrait data or CG trigger — skipping painter AI');
      return null;
    }
    console.log('[Painter] Work to do: hasPortrait=', hasPortrait, 'hasCG=', hasCG);

