  /**
   * Apply preset parameters to a provider object (returns a new copy).
   * Only parameters listed in the preset's enabled_params are applied.
   * If no preset is selected or preset has no params, returns provider unchanged.
   */
  /**
   * Coerce a row value into an array.
   *
   * Preset rows are not consistent about this: some store real JSON (`["temperature","top_p"]`),
   * but SillyTavern-imported presets store the JSON ARRAY AS A STRING — `'["temperature","top_p"]'`.
   * `new Set('[...]')` silently iterates the CHARACTERS instead, so every lookup missed and the
   * whole preset was discarded (max_tokens stayed at the provider's value). Accept every shape.
   */
  function coerceStringArray(value) {
    if (Array.isArray(value)) return value;
    if (typeof value !== 'string') return [];
    const t = value.trim();
    if (!t) return [];
    if (t.startsWith('[')) {
      try {
        const parsed = JSON.parse(t);
        if (Array.isArray(parsed)) return parsed.map(String);
      } catch { /* fall through to comma-splitting */ }
      // `["a","b"` style damage: strip brackets/quotes and split.
      return t.replace(/^\[|\]$/g, '').split(',').map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
    }
    return t.split(',').map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
  }

  /** Coerce a preset `data` column into an object (accepts an object or a JSON string). */
  function coercePresetData(value) {
    if (value && typeof value === 'object') return value;
    if (typeof value !== 'string' || !value.trim()) return {};
    try {
      const parsed = JSON.parse(value);
      return (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) ? parsed : {};
    } catch {
      return {};
    }
  }

  function applyPresetToProvider(provider, presetSettingKey) {
    try {
      const presetSetting = db.prepare("SELECT value FROM app_settings WHERE key = ?").get(presetSettingKey);
      if (!presetSetting || !presetSetting.value) return provider;
      const preset = db.prepare("SELECT * FROM api_presets WHERE id = ? AND preset_type = 'chat'").get(presetSetting.value);
      if (!preset) return provider;
      const presetData = coercePresetData(preset.data);
      const enabledParams = new Set(coerceStringArray(preset.enabled_params));
      if (enabledParams.size === 0) {
        console.warn('[Preset] enabled_params is empty/unreadable for preset', preset.id,
          '— nothing applied. Raw value:', JSON.stringify(preset.enabled_params)?.slice(0, 120));
        return provider;
      }
      const overrides = {};
      for (const key of enabledParams) {
        if (presetData[key] !== undefined) {
          overrides[key] = presetData[key];
        }
      }
      if (Object.keys(overrides).length === 0) {
        console.warn('[Preset] Preset', preset.id, 'enabled', [...enabledParams].join('/'),
          'but none of those keys exist in its data — using provider values.');
        return provider;
      }
      console.log('[Preset] Applying preset params to provider:', Object.keys(overrides).join(', '),
        '| max_tokens:', overrides.max_tokens ?? '(not in preset)');
      return { ...provider, ...overrides };
    } catch (e) {
      console.warn('[Preset] Error applying preset params:', e.message);
      return provider;
    }
  }

