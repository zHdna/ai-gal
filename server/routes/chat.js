// ============ Character-card name matching ============
/**
 * Normalize a character name for fuzzy comparison:
 * - strip full-width (U+3000) and regular whitespace
 * - strip trailing CJK/ASCII punctuation artifacts the model often appends
 * This is used to keep the character CARD itself (which is the scenario/title,
 * not a dialogue character) out of the roster even when the butler/deep-fallback
 * emits a name variant (extra space, trailing 。, etc.).
 */
function normalizeName(s) {
  return (s || '')
    .replace(/[　\s]+/g, '')                       // full-width + regular spaces
    .replace(/[。、，！？；：·.…・]+$/g, '')        // trailing punctuation
    .trim();
}

