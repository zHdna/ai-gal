// Fields to extract, in order (种族性别 is race_gender format, e.g. human_girl)
const PORTRAIT_TAG_FIELDS = ['种族性别', '年龄', '发色', '发长', '发型', '刘海', '瞳色', '身高', '身材', '罩杯', '上衣'];
