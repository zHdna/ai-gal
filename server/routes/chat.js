// Helper: is a string a usable english name?
// = 非空、长度合理、纯 ASCII、且至少含一个英文字母（挡掉 '---'、'123' 这类垃圾值）。
function isCleanAsciiName(s) {
  if (typeof s !== 'string') return false;
  const t = s.trim();
  return t.length > 0 && t.length <= 48 && /^[\x00-\x7F]+$/.test(t) && /[A-Za-z]/.test(t);
}
