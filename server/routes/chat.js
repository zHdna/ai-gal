/**
 * Safely join save.save_path with segments and validate against path traversal.
 * Logs and throws if the resolved path escapes savePath; existing try/catch
 * blocks around each call site handle the throw without interrupting the flow.
 */
function safeSavePath(savePath, ...segments) {
  const fullPath = path.join(savePath, ...segments);
  if (!isPathWithin(savePath, fullPath)) {
    console.error('[Security] Path traversal detected:', fullPath, 'outside base:', savePath);
    throw new Error('Path traversal detected');
  }
  return fullPath;
}

