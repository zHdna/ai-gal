// ============ Token Estimation ============
/**
 * Estimate token count for text.
 * Chinese: ~1.5 chars/token, English: ~4 chars/token
 * This is a rough approximation; actual token count depends on tokenizer.
 */
function estimateTokens(text) {
  if (!text) return 0;
  const cn = (text.match(/[\u4e00-\u9fff\u3000-\u303f\uff00-\uffef]/g) || []).length;
  const en = text.length - cn;
  return Math.ceil(cn / 1.5 + en / 4);
}

/**
 * Estimate token count for a messages array (for API context)
 */
function estimateMessagesTokens(messages) {
  let total = 0;
  for (const msg of messages) {
    // Each message has overhead: role tags, formatting ≈ 4 tokens
    total += 4;
    if (msg.content) total += estimateTokens(msg.content);
    if (msg.name) total += estimateTokens(msg.name);
  }
  return total;
}

// ============ Image Tag Normalization ============
const CUP_MAP = {
  'a_cup': 'small_breasts', 'b_cup': 'small_breasts',
  'c_cup': 'medium_breasts', 'd_cup': 'medium_breasts', 'e_cup': 'medium_breasts',
  'f_cup': 'big_breasts', 'g_cup': 'big_breasts', 'h_cup': 'big_breasts',
};
const BODY_PART_TAGS = /^(arm|arms|hand|hands|leg|legs|foot|feet|thigh|thighs|calf|calves|knee|ankle|shoulder|neck|back|chest|breasts?|hips?|waist|belly|navel|butt|ass)/i;

function normalizeImageTags(prompt, portraitData) {
  if (!prompt) return prompt;
  let tags = prompt.split(',').map(t => t.trim()).filter(Boolean);

  // 1. Age → tag normalization (support both 'age' old format and '年龄段'/'年龄' new format)
  const ageValue = portraitData?.age || portraitData?.年龄段 || portraitData?.年龄;
  if (ageValue) {
    const age = ageValue.toString().toLowerCase().trim();
    let ageTag = null;
    if (/^\d+$/.test(age)) {
      const n = parseInt(age);
      if (n < 16) ageTag = 'loli';
      else if (n <= 30) ageTag = 'teen';
      else if (n <= 55) ageTag = 'milf';
      else ageTag = 'old';
    } else if (['loli', 'child'].includes(age)) ageTag = 'loli';
    else if (['teen', 'young', 'youth'].includes(age)) ageTag = 'teen';
    else if (['adult', 'mature', 'milf'].includes(age)) ageTag = 'milf';
    else if (['old', 'elder', 'elderly'].includes(age)) ageTag = 'old';

    if (ageTag) {
      // Remove existing conflicting age tags
      tags = tags.filter(t => !/^(loli|teen|milf|old|child|young|adult|mature|elder|youth)$/i.test(t.trim()));
      // Insert after gender tag
      const idx = tags.findIndex(t => t.includes('1girl') || t.includes('1boy') || t.includes('1futa') || t.includes('solo'));
      if (idx >= 0) tags.splice(idx + 1, 0, ageTag);
      else tags.splice(2, 0, ageTag);
    }
  }

  // 2. Cup size → breast size normalization
  for (let i = tags.length - 1; i >= 0; i--) {
    const t = tags[i].toLowerCase().replace(/[\s+]+/g, '_').trim();
    for (const [cup, replacement] of Object.entries(CUP_MAP)) {
      if (t === cup || t === cup.replace('_cup', '') + '_cup') {
        tags[i] = replacement;
        break;
      }
    }
    // Also match patterns like "A cup", "B-cup" etc.
    const cupMatch = tags[i].match(/^([a-h])[\s_-]?cup$/i);
    if (cupMatch) {
      const key = cupMatch[1].toLowerCase() + '_cup';
      if (CUP_MAP[key]) tags[i] = CUP_MAP[key];
    }
  }
  // Deduplicate breast tags
  const breastTags = tags.filter(t => /^(small|medium|big)_breasts$/i.test(t.trim()));
  if (breastTags.length > 1) {
    // Keep only the last one
    let seen = false;
    tags = tags.filter(t => {
      if (/^(small|medium|big)_breasts$/i.test(t.trim())) {
        if (seen) return false;
        seen = true;
      }
      return true;
    });
  }

  // 3. Body part tags: limit to 1 body part tag max
  let bodyPartCount = 0;
  tags = tags.filter(t => {
    if (BODY_PART_TAGS.test(t.trim())) {
      bodyPartCount++;
      return bodyPartCount <= 1;
    }
    return true;
  });

  return tags.join(', ');
}

