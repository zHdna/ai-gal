  /**
   * Calculate token stats for the given messages array
   * Returns { contextTokens, systemTokens, historyTokens, newContentTokens }
   */
  function calculateTokenStats(messages) {
    let systemTokens = 0;
    let historyTokens = 0;
    let newContentTokens = 0;
    let inHistory = false;
    let lastUserFound = false;

    // System prompt is always messages[0]
    if (messages.length > 0 && messages[0].role === 'system') {
      systemTokens = estimateTokens(messages[0].content) + 4;
    }

    // History: messages[1] to messages[length-2] (before last user message)
    // Last user message: messages[length-1]
    for (let i = 1; i < messages.length; i++) {
      if (i === messages.length - 1 && messages[i].role === 'user') {
        newContentTokens = estimateTokens(messages[i].content) + 4;
      } else {
        historyTokens += estimateTokens(messages[i].content) + 4;
      }
    }

    const contextTokens = systemTokens + historyTokens + newContentTokens;
    return { contextTokens, systemTokens, historyTokens, newContentTokens };
  }

  /**
   * Read/write cumulative token stats from save folder
   * @param {string} conversation_id - Conversation ID
   * @param {number} addTokens - Tokens to add (0 = read only)
   * @returns {{ cumulativeTotal: number }} - Cumulative total tokens for this conversation
   */
  function updateCumulativeTokens(conversation_id, addTokens = 0) {
    try {
      const save = db.prepare('SELECT * FROM saves WHERE conversation_id = ? ORDER BY created_at DESC LIMIT 1').get(conversation_id);
      if (!save) return { cumulativeTotal: 0 };

      fs.mkdirSync(save.save_path, { recursive: true });
      const statsPath = safeSavePath(save.save_path, 'token_stats.json');

      let stats = { cumulativeTotal: 0 };
      try {
        const existing = fs.readFileSync(statsPath, 'utf-8');
        stats = JSON.parse(existing);
        if (typeof stats.cumulativeTotal !== 'number') stats.cumulativeTotal = 0;
      } catch { /* new file */ }

      if (addTokens > 0) {
        stats.cumulativeTotal += addTokens;
        fs.writeFileSync(statsPath, JSON.stringify(stats, null, 2), 'utf-8');
      }

      return stats;
    } catch (e) {
      console.error('[TokenStats] Error:', e.message);
      return { cumulativeTotal: 0 };
    }
  }

  // Strip the ### summarize section from an assistant message. summarize is re-injected
  // separately via the memory/event_log block, so keeping it in history duplicates tokens
  // and bloats the prefix (hurting DeepSeek prefix-cache hit rate).
  function stripSummarizeSection(text) {
    if (!text) return text;
    // Remove "### summarize" heading + its content up to the next ### heading or end-of-text
    let out = text.replace(/###\s*summarize\s*\n[\s\S]*?(?=\n###\s|$)/gi, '');
    // Collapse trailing blank lines left behind
    out = out.replace(/\n{3,}/g, '\n\n').replace(/\s+$/, '').trim();
    return out;
  }

  // Trim the event_log memory to the last N data rows (keeping the markdown table header)
  // so the per-turn "miss" portion stays bounded instead of growing unboundedly every turn.
  function trimEventLog(log, maxRows) {
    if (!log || typeof log !== 'string') return log || '';
    const lines = log.split('\n');
    // Locate the table separator row (|---|---|) to preserve header structure
    let headerEnd = -1;
    for (let i = 0; i < lines.length; i++) {
      if (/^\s*\|[\s:|-]+\|/.test(lines[i])) { headerEnd = i; break; }
    }
    if (headerEnd === -1) {
      // Not a markdown table — keep the last (maxRows * 2) lines as a best effort
      return lines.slice(-(maxRows * 2)).join('\n');
    }
    const header = lines.slice(0, headerEnd + 1);
    const dataRows = lines.slice(headerEnd + 1).filter(l => l.trim() && l.includes('|'));
    const kept = dataRows.slice(-maxRows);
    return [...header, ...kept].join('\n');
  }

