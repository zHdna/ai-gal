/**
 * Try to extract portrait field data for a character from the main AI's ### portrait section(s).
 * Returns a roster-entry-like object or null if not found.
 */
function extractPortraitFromText(characterName, fullText) {
  try {
    const pMatches = fullText.matchAll(/###\s*portrait\s*\n([\s\S]*?)(?=\n###|\n*$)/g);
    for (const pMatch of pMatches) {
      const rawBody = pMatch[1].trim();
      let pData = {};

      // Check if body is JSON format
      if (rawBody.startsWith('{') && rawBody.endsWith('}')) {
        try { pData = JSON.parse(rawBody); } catch {}
      }

      // If JSON parse failed or not JSON, try key:value line format
      if (Object.keys(pData).length === 0) {
        rawBody.split('\n').forEach(line => {
          const idx = line.indexOf(':');
          if (idx > 0) pData[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
          else {
            const idx2 = line.indexOf('：');
            if (idx2 > 0) pData[line.slice(0, idx2).trim()] = line.slice(idx2 + 1).trim();
          }
        });
      }
      // Match by name (exact or fuzzy)
      const pName = pData.name || pData['name'];
      if (pName && (pName === characterName || pName.includes(characterName) || characterName.includes(pName))) {
        // Convert to roster entry format
        return {
          name: characterName,
          种族性别: pData['种族性别'] || 'human_girl',
          年龄: pData['年龄'] || '',
          发色: pData['发色'] || '',
          发长: pData['发长'] || '',
          发型: pData['发型'] || pData['发长'] || '',
          刘海: pData['刘海'] || '',
          瞳色: pData['瞳色'] || '',
          身高: pData['身高'] || '',
          身材: pData['身材'] || '',
          罩杯: pData['罩杯'] || '',
          上衣: pData['上衣'] || '',
          下装: pData['下装'] || '',
          性经验: pData['性经验'] || '',
          贞操观: pData['贞操观'] || '',
          社交性: pData['社交性'] || '',
          智商: pData['智商'] || '',
          道德: pData['道德'] || '',
          简要介绍: pData['简要介绍'] || '',
          avatar: 'pending',
          generated_at: new Date().toISOString()
        };
      }
    }
  } catch {}
  return null;
}

