const GENDER_TAG_MAP = {
  'girl': '1girl',
  'boy': '1boy',
  'futa': '1futa',
};
// Known gender words used to parse 种族性别 (race_gender format)
const GENDER_WORDS = ['futa', 'girl', 'boy'];
// 'pending' avatars older than this are treated as dead triggers (retryable) instead of
// in-flight generations. Real ComfyUI generations complete within ~5 minutes.
const PENDING_STALE_MS = 30 * 60 * 1000;
// Race part of 种族性别 → additional danbooru tags (non-human only)
const RACE_TAG_MAP = {
  'elf': 'elf, pointy_ears',
  'dwarf': 'dwarf',
  'orc': 'orc',
  'demon': 'demon, horns',
  'vampire': 'vampire, fangs',
  'angel': 'angel, wings',
  'catgirl': 'cat_ears, cat_tail',
  'foxgirl': 'fox_ears, fox_tail',
  'robot': 'robot, mechanical',
  'cat_furry': 'cat_ears, cat_tail, furry',
  'dog_furry': 'dog_ears, dog_tail, furry',
  '妖': 'fox_ears, supernatural',
  '灵兽': 'beast, supernatural',
  '精怪': 'supernatural',
};

function buildPortraitPrompt(rosterEntry, qualityPrefix) {
  if (!rosterEntry) return '';
  const prefix = qualityPrefix || PORTRAIT_QUALITY_PREFIX;
  const tags = [];

  for (const field of PORTRAIT_TAG_FIELDS) {
    const val = rosterEntry[field];
    if (!val || val.trim() === '' || val === 'none') continue;

    if (field === '种族性别') {
      // Format: race_gender (e.g. human_girl, elf_boy, cat_furry_futa)
      const combined = val.trim().toLowerCase();
      const genderPart = GENDER_WORDS.find(g => combined.endsWith('_' + g));
      const racePart = genderPart
        ? combined.slice(0, combined.length - genderPart.length - 1) // Strip _gender suffix
        : combined;
      const actualGender = genderPart || combined;

      // 1. Danbooru gender tag (1girl/1boy/1futa)
      const genderTag = GENDER_TAG_MAP[actualGender] || actualGender;
      tags.push(genderTag);

      // 2. Race tags (non-human)
      if (racePart && racePart !== 'human' && racePart !== '人类') {
        const raceMapped = RACE_TAG_MAP[racePart];
        if (raceMapped) tags.push(...raceMapped.split(',').map(t => t.trim()));
        else tags.push(racePart);
      }
    } else if (field === '罩杯') {
      // Skip if 'none' (male characters)
      if (val.trim().toLowerCase() !== 'none') {
        tags.push(val.trim());
      }
    } else {
      // Direct tag value
      tags.push(val.trim());
    }
  }

  // Fallback: if no gender tag was added (种族性别 field missing or empty), infer from other fields
  const hasGenderTag = tags.some(t => /^(1girl|1boy|1futa)$/i.test(t));
  if (!hasGenderTag) {
    const cup = (rosterEntry['罩杯'] || '').toLowerCase();
    const body = (rosterEntry['身材'] || '').toLowerCase();
    const top = (rosterEntry['上衣'] || '').toLowerCase();
    const inferredGender = (cup === 'none' || body === 'muscular' || /suit|西装|shirt/i.test(top)) ? '1boy' : '1girl';
    // Insert after quality prefix (position 0) or at beginning
    const genderIdx = tags.findIndex(t => /^(portrait|solo|close-up)$/i.test(t));
    if (genderIdx >= 0) tags.splice(genderIdx, 0, inferredGender);
    else tags.unshift(inferredGender);
    console.log('[Portrait] Gender tag inferred from fields:', inferredGender, '(cup:', cup, 'body:', body, 'top:', top, ')');
  }

  if (tags.length === 0) return '';
  return prefix + tags.join(',');
}

